import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import matter from 'gray-matter';

const root = process.cwd();
const collections = ['art', 'lifestyle', 'travel'];
const outputPath = join(root, 'supabase', 'seed-content.sql');

const rows = [];

for (const collection of collections) {
  const collectionDir = join(root, 'src', 'content', collection);
  const files = await listMarkdownFiles(collectionDir);

  for (const filePath of files) {
    const source = await readFile(filePath, 'utf8');
    const parsed = matter(source);
    const slug = filePath.split('/').pop().replace(/\.md$/, '');

    rows.push({
      collection,
      slug,
      published: parsed.data.published ?? true,
      data: parsed.data,
      body_markdown: parsed.content.trim()
    });
  }
}

const statements = rows
  .map((row) => {
    return `insert into public.content_entries (collection, slug, published, data, body_markdown)
values (${sql(row.collection)}, ${sql(row.slug)}, ${row.published ? 'true' : 'false'}, ${jsonb(row.data)}, ${sql(row.body_markdown)})
on conflict (collection, slug) do update set
  published = excluded.published,
  data = excluded.data,
  body_markdown = excluded.body_markdown,
  body_html = null;`;
  })
  .join('\n\n');

await mkdir(join(root, 'supabase'), { recursive: true });
await writeFile(
  outputPath,
  `-- Generated by npm run supabase:seed:generate\n-- Source: src/content/**/*.md\n\n${statements}\n`,
  'utf8'
);

console.log(`Wrote ${rows.length} content rows to ${relative(root, outputPath)}`);

async function listMarkdownFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await listMarkdownFiles(fullPath)));
    } else if (entry.isFile() && entry.name.endsWith('.md')) {
      files.push(fullPath);
    }
  }

  return files.sort();
}

function sql(value) {
  if (value === null || value === undefined) {
    return 'null';
  }

  return `'${String(value).replaceAll("'", "''")}'`;
}

function jsonb(value) {
  return `${sql(JSON.stringify(value))}::jsonb`;
}
